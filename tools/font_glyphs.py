def check():
    for c in range(32, 127):
        assert chr(c) in G, 'missing %r' % chr(c)

def ada():
    out = []
    out.append('--  Generated by tools/font_glyphs.py: edit the pictures there, not here.')
    out.append('--  One glyph per entry: 9 rows (0-6 above the baseline, 7-8 below),')
    out.append("--  '#' ink.  Rows are padded to 5 columns; Width is the real width.")
    out.append('package Castle.Font_Data with Pure is')
    out.append('')
    out.append('   Rows : constant := 9;')
    out.append('   Max_W : constant := 5;')
    out.append('   subtype Row is String (1 .. Max_W);')
    out.append('   type Picture is array (0 .. Rows - 1) of Row;')
    out.append('   type Glyph is record')
    out.append('      Width : Natural;')
    out.append('      Pic   : Picture;')
    out.append('   end record;')
    out.append('')
    out.append('   First : constant := 32;')
    out.append('   Last  : constant := 127;   --  127 stands in for the degree sign')
    out.append('   Glyphs : constant array (First .. Last) of Glyph :=')
    out.append('     [')
    keys = [chr(c) for c in range(32, 127)] + ['\xb0']
    for i, ch in enumerate(keys):
        rows = G[ch]
        w = len(rows[0])
        code = 127 if ch == '\xb0' else ord(ch)
        name = 'degree' if ch == '\xb0' else repr(ch)
        pic = ', '.join('"%s"' % r.ljust(5, '.') for r in rows)
        sep = ',' if i < len(keys) - 1 else ']; '
        out.append('      %3d => (%d, [%s])%s   -- %s' % (code, w, pic, sep, name))
    out.append('')
    out.append('end Castle.Font_Data;')
    return '\n'.join(out) + '\n'

def png(path, scale=4):
    import zlib, struct
    keys = [chr(c) for c in range(32, 127)] + ['\xb0']
    cols = 16
    cw, chh = 7, 11
    rows_n = (len(keys) + cols - 1) // cols
    W, H = cols * cw * scale, rows_n * chh * scale
    img = [[(40, 36, 32)] * W for _ in range(H)]
    for i, ch in enumerate(keys):
        ox, oy = (i % cols) * cw, (i // cols) * chh
        for y in range(chh):
            for x in range(cw):
                if y == 8:   # baseline guide under row 6
                    pass
        for y, r in enumerate(G[ch]):
            for x, c in enumerate(r):
                col = (240, 230, 200) if c == '#' else ((60, 54, 48) if y < 7 else (52, 44, 60))
                for sy in range(scale):
                    for sx in range(scale):
                        img[(oy + 1 + y) * scale + sy][(ox + 1 + x) * scale + sx] = col
    raw = b''.join(b'\x00' + bytes(v for p in row for v in p) for row in img)
    def chunk(t, d):
        c = struct.pack('>I', len(d)) + t + d
        return c + struct.pack('>I', zlib.crc32(t + d) & 0xffffffff)
    data = b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 2, 0, 0, 0)) \
        + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b'')
    open(path, 'wb').write(data)

